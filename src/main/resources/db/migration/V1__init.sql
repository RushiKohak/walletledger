-- WalletLedger schema.
-- All money columns are BIGINT minor units (paise/cents) next to a 3-letter currency code.
-- Nothing in this schema stores money as a floating point number.

CREATE TABLE accounts (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    owner_name VARCHAR(255)  NOT NULL,
    currency   VARCHAR(3)    NOT NULL,
    balance    BIGINT        NOT NULL DEFAULT 0,
    type       VARCHAR(16)   NOT NULL,
    version    BIGINT        NOT NULL DEFAULT 0,
    created_at TIMESTAMPTZ   NOT NULL DEFAULT now(),
    CONSTRAINT accounts_type_check CHECK (type IN ('USER', 'SYSTEM')),
    CONSTRAINT accounts_currency_check CHECK (currency = upper(currency) AND char_length(currency) = 3),
    -- User money may never go negative. The SYSTEM treasury is allowed to go negative,
    -- because it is the counterparty of every deposit and does not hold real money.
    CONSTRAINT accounts_balance_non_negative_check CHECK (type = 'SYSTEM' OR balance >= 0)
);

-- Exactly one treasury account per currency, so deposits always have one SYSTEM counterparty.
CREATE UNIQUE INDEX accounts_one_treasury_per_currency_idx
    ON accounts (currency)
    WHERE type = 'SYSTEM';

CREATE TABLE ledger_transactions (
    id              UUID         PRIMARY KEY,
    idempotency_key VARCHAR(255) NOT NULL,
    request_hash    VARCHAR(64)  NOT NULL,
    type            VARCHAR(16)  NOT NULL,
    status          VARCHAR(16)  NOT NULL,
    created_at      TIMESTAMPTZ  NOT NULL DEFAULT now(),
    -- The database, not the application, is the authority on "one transaction per idempotency key".
    CONSTRAINT ledger_transactions_idempotency_key_unique UNIQUE (idempotency_key),
    CONSTRAINT ledger_transactions_type_check CHECK (type IN ('DEPOSIT', 'TRANSFER')),
    -- A transaction row only exists if it committed, so POSTED is the only reachable state today.
    CONSTRAINT ledger_transactions_status_check CHECK (status IN ('POSTED'))
);

-- Append-only: rows are inserted once and never updated or deleted.
CREATE TABLE ledger_entries (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    transaction_id UUID        NOT NULL REFERENCES ledger_transactions (id),
    account_id     BIGINT      NOT NULL REFERENCES accounts (id),
    direction      VARCHAR(8)  NOT NULL,
    amount         BIGINT      NOT NULL,
    created_at     TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT ledger_entries_direction_check CHECK (direction IN ('DEBIT', 'CREDIT')),
    CONSTRAINT ledger_entries_amount_positive_check CHECK (amount > 0)
);

CREATE INDEX ledger_entries_transaction_id_idx ON ledger_entries (transaction_id);
CREATE INDEX ledger_entries_account_id_id_idx ON ledger_entries (account_id, id);
